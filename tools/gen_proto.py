#!/usr/bin/env python3
"""Generate the link protocol code for both sides from proto/messages.yaml.

    python tools/gen_proto.py          # write generated files
    python tools/gen_proto.py --check  # exit 1 if any generated file is stale (CI)

Why generate instead of hand-writing both sides: v1 kept the Python packer and
the firmware notes in sync by hand. Here one schema produces the Python
dataclasses, the C++ structs, and golden byte vectors that the C++ unit tests
decode, so the two sides cannot disagree about a single byte.
"""

from __future__ import annotations

import argparse
import json
import sys
import types
import zlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "proto" / "messages.yaml"
PY_OUT = ROOT / "turret" / "link" / "messages.py"
CPP_OUT = ROOT / "firmware" / "lib" / "proto" / "src" / "messages_gen.h"
GOLDEN_OUT = ROOT / "firmware" / "test" / "test_proto" / "golden.h"

HEADER = "GENERATED by tools/gen_proto.py from proto/messages.yaml. Do not edit by hand."

# type -> (struct code, size, C type, python default)
SCALARS = {
    "u8": ("B", 1, "uint8_t", "0"),
    "u16": ("H", 2, "uint16_t", "0"),
    "u32": ("I", 4, "uint32_t", "0"),
    "u64": ("Q", 8, "uint64_t", "0"),
    "i8": ("b", 1, "int8_t", "0"),
    "i16": ("h", 2, "int16_t", "0"),
    "i32": ("i", 4, "int32_t", "0"),
    "f32": ("f", 4, "float", "0.0"),
}


def str_len(t: str) -> int | None:
    if t.startswith("str"):
        return int(t[3:])
    return None


def field_size(t: str) -> int:
    n = str_len(t)
    return n if n is not None else SCALARS[t][1]


def load_schema() -> list[dict]:
    data = yaml.safe_load(SCHEMA.read_text())
    msgs = data["messages"]
    ids = set()
    names = set()
    for m in msgs:
        if m["id"] in ids or m["name"] in names:
            raise SystemExit(f"duplicate message id/name: {m['name']}")
        ids.add(m["id"])
        names.add(m["name"])
        if m["dir"] not in ("j2e", "e2j"):
            raise SystemExit(f"{m['name']}: dir must be j2e or e2j")
        size = 0
        for f in m["fields"]:
            if f["type"] not in SCALARS and str_len(f["type"]) is None:
                raise SystemExit(f"{m['name']}.{f['name']}: unknown type {f['type']}")
            size += field_size(f["type"])
        if size > 64:
            raise SystemExit(f"{m['name']}: payload {size} B exceeds 64 B")
        m["size"] = size
    return msgs


def proto_hash(msgs: list[dict]) -> int:
    canon = [
        {
            "name": m["name"],
            "id": m["id"],
            "dir": m["dir"],
            "fields": [[f["name"], f["type"]] for f in m["fields"]],
        }
        for m in msgs
    ]
    return zlib.crc32(json.dumps(canon, sort_keys=True, separators=(",", ":")).encode())


# ----------------------------------------------------------------------------- Python


def gen_python(msgs: list[dict], h: int) -> str:
    out = [
        f'"""{HEADER}"""',
        "",
        "# ruff: noqa: E501",
        "from __future__ import annotations",
        "",
        "import struct",
        "from dataclasses import dataclass",
        "from typing import ClassVar, Union",
        "",
        f"PROTO_HASH = 0x{h:08X}",
        "",
    ]
    for m in msgs:
        fmt = "<" + "".join(
            f"{str_len(f['type'])}s" if str_len(f["type"]) else SCALARS[f["type"]][0] for f in m["fields"]
        )
        out += ["", "@dataclass", f"class {m['name']}:"]
        doc = " ".join(str(m.get("doc", m["name"])).split())
        out.append(f'    """{doc}"""')
        out.append("")
        out.append(f"    ID: ClassVar[int] = 0x{m['id']:02X}")
        out.append(f'    DIR: ClassVar[str] = "{m["dir"]}"')
        out.append(f"    SIZE: ClassVar[int] = {m['size']}")
        out.append(f'    _S: ClassVar[struct.Struct] = struct.Struct("{fmt}")')
        for f in m["fields"]:
            if str_len(f["type"]):
                out.append(f'    {f["name"]}: str = ""')
            elif f["type"] == "f32":
                out.append(f"    {f['name']}: float = 0.0")
            else:
                out.append(f"    {f['name']}: int = 0")
        args = []
        for f in m["fields"]:
            n = str_len(f["type"])
            if n:
                args.append(f'self.{f["name"]}.encode("utf-8")[:{n}]')
            else:
                args.append(f"self.{f['name']}")
        out.append("")
        out.append("    def pack(self) -> bytes:")
        out.append(f"        return self._S.pack({', '.join(args)})")
        out.append("")
        out.append("    @classmethod")
        out.append(f"    def unpack(cls, b: bytes) -> {m['name']}:")
        out.append("        v = list(cls._S.unpack(b))")
        for i, f in enumerate(m["fields"]):
            if str_len(f["type"]):
                out.append(f'        v[{i}] = v[{i}].split(b"\\x00", 1)[0].decode("utf-8", "replace")')
        out.append("        return cls(*v)")
        out.append("")
    names = ", ".join(m["name"] for m in msgs)
    out.append("")
    out.append(f"Message = Union[{names}]")
    out.append("")
    out.append("BY_ID: dict[int, type] = {")
    for m in msgs:
        out.append(f"    0x{m['id']:02X}: {m['name']},")
    out.append("}")
    out.append("")
    return "\n".join(out)


# ----------------------------------------------------------------------------- C++


def gen_cpp(msgs: list[dict], h: int) -> str:
    out = [
        f"// {HEADER}",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        "namespace proto {",
        "",
        f"static constexpr uint32_t PROTO_HASH = 0x{h:08X}u;",
        "",
    ]
    for m in msgs:
        doc = " ".join(str(m.get("doc", "")).split())
        if doc:
            out.append(f"// {doc}")
        out.append(f"struct {m['name']} {{")
        out.append(f"  static constexpr uint8_t ID = 0x{m['id']:02X};")
        out.append(f"  static constexpr size_t SIZE = {m['size']};")
        for f in m["fields"]:
            n = str_len(f["type"])
            if n:
                out.append(f"  char {f['name']}[{n}] = {{0}};")
            else:
                ctype = SCALARS[f["type"]][2]
                init = "0.0f" if f["type"] == "f32" else "0"
                out.append(f"  {ctype} {f['name']} = {init};")
        out.append("")
        out.append("  size_t encode(uint8_t* b) const {")
        out.append("    size_t o = 0;")
        for f in m["fields"]:
            sz = field_size(f["type"])
            out.append(f"    memcpy(b + o, &{f['name']}, {sz}); o += {sz};")
        out.append("    return o;")
        out.append("  }")
        out.append("")
        out.append(f"  static bool decode(const uint8_t* b, size_t n, {m['name']}& m) {{")
        out.append("    if (n != SIZE) return false;")
        out.append("    size_t o = 0;")
        for f in m["fields"]:
            sz = field_size(f["type"])
            out.append(f"    memcpy(&m.{f['name']}, b + o, {sz}); o += {sz};")
        if not m["fields"]:
            out.append("    (void)b;")
        out.append("    return true;")
        out.append("  }")
        out.append("};")
        out.append("")
    out.append("}  // namespace proto")
    out.append("")
    return "\n".join(out)


# ----------------------------------------------------------------------------- golden


def sample_value(t: str, i: int):
    n = str_len(t)
    if n:
        return "turret v2 golden"
    return {
        "u8": 0x12 + i,
        "u16": 0x0100 + i,  # low byte 0x00 on the first field exercises COBS
        "u32": 0x89ABCD00 + i,
        "u64": 0x0123456789AB0000 + i,
        "i8": -5 - i,
        "i16": -1234 - i,
        "i32": -123456 - i,
        "f32": (1.5 + 0.25 * i) * (-1 if i % 2 else 1),
    }[t]


def cpp_literal(t: str, v) -> str:
    if t == "f32":
        return f"{v!r}f"
    if t == "u64":
        return f"0x{v:016X}ull"
    if t in ("u32",):
        return f"0x{v:08X}u"
    return str(v)


def gen_golden(msgs: list[dict], py_src: str) -> str:
    sys.path.insert(0, str(ROOT))
    from turret.link.framing import encode_frame

    mod = types.ModuleType("_gen_messages")
    sys.modules[mod.__name__] = mod  # dataclasses looks the module up by name
    exec(compile(py_src, "messages.py", "exec"), mod.__dict__)

    out = [
        f"// {HEADER}",
        "// Frames below were produced by the PYTHON encoder; the C++ test must decode",
        "// them to the expected fields and re-encode them to the same bytes.",
        "#pragma once",
        "",
        '#include "framing.h"',
        '#include "messages_gen.h"',
        "#include <unity.h>",
        "",
        "namespace golden {",
        "",
    ]
    runs = []
    for m in msgs:
        cls = getattr(mod, m["name"])
        vals = {f["name"]: sample_value(f["type"], i) for i, f in enumerate(m["fields"])}
        msg = cls(**vals)
        frame = encode_frame(cls.ID, msg.pack())
        name = m["name"]
        out.append(f"static const uint8_t {name}_FRAME[] = {{")
        hexes = [f"0x{b:02X}" for b in frame]
        for k in range(0, len(hexes), 12):
            out.append("    " + ", ".join(hexes[k : k + 12]) + ",")
        out.append("};")
        out.append("")
        out.append(f"inline void test_golden_{name}() {{")
        out.append(f"  proto::{name} e;")
        for f in m["fields"]:
            v = vals[f["name"]]
            if str_len(f["type"]):
                out.append(f'  strncpy(e.{f["name"]}, "{v}", sizeof(e.{f["name"]}));')
            else:
                out.append(f"  e.{f['name']} = {cpp_literal(f['type'], v)};")
        out.append("  proto::FrameDecoder dec;")
        out.append("  int got = 0;")
        out.append(f"  for (size_t i = 0; i < sizeof({name}_FRAME); ++i) {{")
        out.append(f"    if (!dec.push({name}_FRAME[i])) continue;")
        out.append("    ++got;")
        out.append(f"    TEST_ASSERT_EQUAL_UINT8(proto::{name}::ID, dec.id());")
        out.append(f"    proto::{name} m;")
        out.append(f"    TEST_ASSERT_TRUE(proto::{name}::decode(dec.payload(), dec.payload_len(), m));")
        for f in m["fields"]:
            out.append(f"    TEST_ASSERT_EQUAL_MEMORY(&e.{f['name']}, &m.{f['name']}, sizeof(m.{f['name']}));")
        out.append("    uint8_t buf[proto::MAX_ENCODED];")
        out.append("    size_t n = proto::encode_frame(m, buf);")
        out.append(f"    TEST_ASSERT_EQUAL_UINT32(sizeof({name}_FRAME), n);")
        out.append(f"    TEST_ASSERT_EQUAL_MEMORY({name}_FRAME, buf, n);")
        out.append("  }")
        out.append("  TEST_ASSERT_EQUAL_INT(1, got);")
        out.append("}")
        out.append("")
        runs.append(f"RUN_TEST(golden::test_golden_{name});")
    out.append("}  // namespace golden")
    out.append("")
    out.append("#define RUN_GOLDEN_TESTS() \\")
    out.append("  do { \\")
    for r in runs:
        out.append(f"    {r} \\")
    out.append("  } while (0)")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()

    msgs = load_schema()
    h = proto_hash(msgs)
    py_src = gen_python(msgs, h)
    outputs = {
        PY_OUT: py_src,
        CPP_OUT: gen_cpp(msgs, h),
        GOLDEN_OUT: gen_golden(msgs, py_src),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if args.check:
        if stale:
            print("stale generated files (run python tools/gen_proto.py):")
            for p in stale:
                print(f"  {p}")
            return 1
        print(f"protocol code up to date (hash 0x{h:08X})")
        return 0
    print(f"protocol hash 0x{h:08X}; wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
